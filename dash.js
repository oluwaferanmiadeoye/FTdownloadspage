      function renderFiles(containerId, fileIds) {
        const container = document.getElementById(containerId);
        if (!container) return;

        container.innerHTML = "";
        if (fileIds.length === 0) {
          container.innerHTML = '<p class="no-files">No files found.</p>';
          return;
        }

        fileIds.forEach((id) => {
          const item = downloadsData.find((item) => item.id === id);
          if (item) {
            const card = document.createElement("div");
            card.className = "file-card";
            card.innerHTML = `
            <img src="${item.thumbnail}" alt="${item.title}">
            <h4>${item.title}</h4>
            <small>${new Date(item.date).toLocaleDateString()}</small>
            <a href="${item.downloadUrl}" download>
              <i class="fas fa-download"></i> Download
            </a>
          `;
            container.appendChild(card);
          }
        });
      }

      document.addEventListener("DOMContentLoaded", () => {
        const downloadedFiles = JSON.parse(
          localStorage.getItem("downloadedFiles") || "[]"
        );
        const libraryFiles = JSON.parse(
          localStorage.getItem("libraryFiles") || "[]"
        );
        renderFiles("downloadedFiles", downloadedFiles);
        renderFiles("libraryFiles", libraryFiles);
      });